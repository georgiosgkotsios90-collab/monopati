def phase_of(left: int | None) -> tuple[str, int]:
    """Επιστρέφει (φάση, εβδομάδα μέσα στη φάση)."""
    if left is None:
        return "build", 0
    if left <= 2:
        return "taper", 2 - left
    if left <= 10:
        return "specific", 10 - left
    if left <= 20:
        return "build", 20 - left
    return "base", max(0, 30 - left)


PHASE_LABEL = {"base": "Βάση", "build": "Ανάπτυξη", "specific": "Ειδική προετοιμασία", "taper": "Αποκλιμάκωση (taper)"}


def _pick(seq, k):
    return seq[min(len(seq) - 1, k // 2)]


def _down(n: int, mode: str, scale: float) -> int:
    if mode == "down":
        n = round(n * 0.65)
    return max(2, round(n * scale))


def quality(slot: str, phase: str, k: int, mode: str, scale: float, race: str) -> tuple[str, str, str]:
    """Διαλειμματικές με τα νορβηγικά πρωτόκολλα (1:30–1:45 με ζέσταμα, εύκολο συμπλήρωμα και αποψύχρανση).

    q1 (Δευτέρα): VO2max: Norwegian 4×4 → 5×4 / 4×5, micro-intervals 30/15, Bakken ανηφόρες.
    q2 (Παρασκευή): κατώφλι: Bakken short threshold (10–12×3') και long threshold (5×6' / 6×5').
    Η Παρασκευή είναι πάντα κατωφλίου (όχι VO2max), επειδή την επομένη ακολουθεί το μακρύ του Σαββάτου.
    scale < 1 όταν η πρόσφατη φόρμα είναι κάτω από το συνηθισμένο σου.
    """
    if phase == "taper":
        if slot == "q1":
            return ("Ελαφριά ποιότητα",
                    "Ζέσταμα 10 λεπτά, 4×2 λεπτά γρήγορη ανηφόρα (ελεγχόμενα), χαλαρή κατηφόρα, 10 λεπτά αποψύχρανση.",
                    "Στο taper κρατάμε την ένταση και κόβουμε 40–60% του όγκου: έτσι διατηρείται η φόρμα και φεύγει η κούραση (Bosquet et al., 2007).")
        return ("Ελαφρύ fartlek", "Άνετο τρέξιμο με 6×1 λεπτό ζωηρά, 2 λεπτά χαλαρά ανάμεσα.",
                "Σύντομα ζωηρά κομμάτια κρατούν τα πόδια «ξύπνια» χωρίς να προσθέτουν κούραση πριν τον αγώνα (Bosquet et al., 2007).")

    if slot == "q1":
        if phase == "base":
            # Κυρίως short threshold· κάθε τρίτη εβδομάδα Bakken ανηφόρες για δύναμη στην ανηφόρα.
            if k % 3 == 2:
                return _short_hill(k, mode, scale)
            return _short_threshold(k, mode, scale, "q1")
        if phase == "build":
            seq = ["4x4", "3015", "4x4", "3015", "5x4", "3015", "4x5", "3015", "5x4", "4x5"]
            pick = seq[min(k, len(seq) - 1)]
            if pick == "3015":
                return _micro(k, mode, scale)
            n, m = {"4x4": (4, 4), "5x4": (5, 4), "4x5": (4, 5)}[pick]
            return _norwegian(n, m, mode, scale)
        # Ειδική φάση: λιγότερη VO2max. Εναλλάξ συντήρηση 4×4 και μεγάλες ανηφόρες στο κατώφλι.
        if k % 2 == 1:
            return _norwegian(4, 4, mode, scale)
        n, m = _pick([(3, 12), (3, 15), (2, 20), (3, 15), (2, 20)], k)
        n = _down(n, mode, scale)
        return (f"Ανηφορικό κατώφλι {n}×{m}'",
                f"Ζέσταμα 15 λεπτά. {n}×{m} λεπτά συνεχούς ανάβασης στο κατώφλι (ζώνη 4). Όπου η κλίση ξεπερνά ~20%, γρήγορο περπάτημα με μπατόν, "
                f"όπως στον αγώνα. Χαλαρό κατέβασμα ανάμεσα. 10 λεπτά αποψύχρανση.",
                f"Το {race} έχει περίπου 2.800 m συνεχούς ανάβασης στα πρώτα 21 km. Μεγάλα διαστήματα ανηφόρας στο κατώφλι "
                "προπονούν ακριβώς αυτή την απαίτηση και την εναλλαγή τρεξίματος/power hiking (Seiler, 2010· Koop, 2016).")

    # q2 (Παρασκευή): πάντα κατώφλι. Εναλλαγή Bakken με τη «σκάλα» που έκανες με το Tzanetakis Lab (2024).
    if phase == "base":
        return _long_threshold(k, mode, scale) if k % 2 == 0 else _ladder(phase, k, mode, scale)
    pick = k % 3
    if pick == 0:
        return _short_threshold(k, mode, scale, "q2")
    if pick == 1:
        return _ladder(phase, k, mode, scale)
    return _long_threshold(k, mode, scale, rolling=(phase == "specific"))


LADDER_MAX_MIN = 45  # συνολικός χρόνος στο κατώφλι στη σκάλα (το 2024 έφτανε τα 65′, πολύ για την ημέρα πριν το μακρύ)


def _ladder(phase: str, k: int, mode: str, scale: float) -> tuple[str, str, str]:
    """Σκάλα κατωφλίου (Tzanetakis Lab): κομμάτια που μικραίνουν, 1′ χαλαρό ανάμεσα, με στόχο παλμών αντί για ρυθμό."""
    total = {"base": 30 + 2 * (k // 2), "build": 36 + 2 * (k // 3)}.get(phase, LADDER_MAX_MIN)
    total = min(LADDER_MAX_MIN, total)
    if mode == "down":
        total = round(total * 0.65)
    total = max(20, round(total * scale))
    ten = 10 if total >= 38 else 0
    six = max(1, round((total - ten - 12) / 6))
    first = "10'+" if ten else ""
    terr = "σε κυματιστό έδαφος, όπως στον αγώνα" if phase == "specific" else "σε επίπεδο ή ήπιο ανάγλυφο"
    return (f"Σκάλα κατωφλίου {first}{six}×6'+3×3'+3×1'",
            f"Ζέσταμα 15 λεπτά με 2 ζωηρά βήματα. {('10 λεπτά, ' if ten else '')}{six}×6 λεπτά, 3×3 λεπτά και 3×1 λεπτό, "
            f"με 1 λεπτό χαλαρό τρέξιμο ανάμεσα ({'2 λεπτά μετά τα 10′' if ten else 'σε όλα'}), {terr}. "
            f"Τα μεγάλα κομμάτια λίγο κάτω από το κατώφλι, τα 3′ στο κατώφλι και τα 1′ ζωηρά. Οδηγός οι παλμοί, όχι ο ρυθμός. 10 λεπτά αποψύχρανση.",
            "Η σκάλα που έκανες με το Tzanetakis Lab το 2024 (25 φορές, σχεδόν όλες ολόκληρες): κομμάτια που μικραίνουν και γίνονται λίγο πιο γρήγορα "
            "κρατούν πολλή ώρα κοντά στο κατώφλι με σύντομη ανάπαυση. Εδώ έχει όριο 45′ στο κατώφλι (τότε έφτανε 65′, δύο φορές την εβδομάδα) "
            "και στόχο παλμών, επειδή ο ρυθμός κατωφλίου στο TrainingPeaks ήταν πιο αργός από τον πραγματικό σου.")


def _norwegian(n: int, m: int, mode: str, scale: float) -> tuple[str, str, str]:
    n = _down(n, mode, scale)
    return (f"Νορβηγικό {n}×{m}'",
            f"Ζέσταμα 15 λεπτά. {n}×{m} λεπτά σε σταθερή ανηφόρα 6–10% με 3 λεπτά χαλαρό τρέξιμο ανάμεσα. "
            f"Κανόνας των 90″: μην ξεκινάς σπριντάροντας. Τα πρώτα 90 δευτερόλεπτα ανεβάζεις σταδιακά τον παλμό "
            f"και το υπόλοιπο κομμάτι το κρατάς στο 90–95% των μέγιστων παλμών (RPE 8,5/10). 10 λεπτά αποψύχρανση.",
            "Το νορβηγικό 4×4 είναι το πρότυπο για την αύξηση του VO2max και του όγκου παλμού της καρδιάς (Helgerud et al., 2007). "
            "Το 5×4 και το 4×5 προσθέτουν χρόνο κοντά στο VO2max όταν υπάρχει βάση. Στην ανηφόρα ο παλμός ανεβαίνει "
            "χωρίς ακραία ταχύτητα, με λιγότερη καταπόνηση σε τένοντες και αρθρώσεις (Barnes et al., 2013).")


def _micro(k: int, mode: str, scale: float) -> tuple[str, str, str]:
    reps = _down(min(10, 8 + k // 3), mode, scale)
    return (f"Micro 30/15: 3×{reps}",
            f"Ζέσταμα 15 λεπτά. 3 σετ των {reps} επαναλήψεων: 30″ δυνατά (RPE 9/10) και 15″ πολύ χαλαρά. "
            f"3 λεπτά χαλαρό τρέξιμο ανάμεσα στα σετ. Οι παλμοί ανεβαίνουν σταδιακά στο 90–95% των μέγιστων. "
            f"Ιδανικά σε ήπια ανηφόρα ή επίπεδο. 10 λεπτά αποψύχρανση.",
            "Τα micro-intervals 30/15 δίνουν περισσότερο συνολικό χρόνο κοντά στο VO2max με λιγότερο γαλακτικό "
            "από τα μεγάλα διαστήματα, και σε μελέτη σε ποδηλάτες αντοχής βελτίωσαν την απόδοση περισσότερο από ισοδύναμα 4×5' (Rønnestad et al., 2015).")


def _short_hill(k: int, mode: str, scale: float) -> tuple[str, str, str]:
    reps = _down(min(20, 15 + k // 2), mode, scale)
    sec = 45 if k < 6 else 60
    return (f"Bakken ανηφόρες {reps}×{sec}″",
            f"Ζέσταμα 15 λεπτά. {reps}×{sec} δευτερόλεπτα σε απότομη ανηφόρα, πολύ δυνατά αλλά με καλή τεχνική (RPE 9/10, 92–96% των μέγιστων παλμών στο τέλος). "
            f"Κατέβα περπατώντας σε 60–75 δευτερόλεπτα. 10 λεπτά αποψύχρανση.",
            "Οι σύντομες, απότομες ανηφόρες της μεθόδου Bakken χτίζουν νευρομυϊκή ισχύ για την ανάβαση και στρατολογούν τις ταχείες ίνες "
            "τύπου IIa, με μικρή καταπόνηση επειδή δεν υπάρχει γρήγορη κατηφόρα (Barnes et al., 2013).")


def _short_threshold(k: int, mode: str, scale: float, slot: str) -> tuple[str, str, str]:
    reps = _down(min(12, 10 + k // 4), mode, scale)
    return (f"Bakken κατώφλι {reps}×3'",
            f"Ζέσταμα 15 λεπτά. {reps}×3 λεπτά στο κατώφλι (LT2, 82–87% των μέγιστων παλμών, «σκληρό αλλά ελεγχόμενο») "
            f"με 60 δευτερόλεπτα χαλαρό τρέξιμο ανάμεσα. Σε επίπεδο ή ήπιο ανάγλυφο. Τελειώνεις νιώθοντας ότι θα έκανες άλλα δύο. "
            f"10 λεπτά αποψύχρανση.",
            "Τα σύντομα κομμάτια κατωφλίου της νορβηγικής μεθόδου (Bakken, Ingebrigtsen) ανεβάζουν την ταχύτητα στο κατώφλι "
            "χωρίς να συσσωρεύουν κούραση, γι' αυτό ταιριάζουν και την ημέρα πριν το μακρύ.")


def _long_threshold(k: int, mode: str, scale: float, rolling: bool = False) -> tuple[str, str, str]:
    n, m = (5, 6) if k % 2 == 0 else (6, 5)
    n = _down(n, mode, scale)
    terr = "σε κυματιστό έδαφος, όπως στον αγώνα" if rolling else "σε ήπιο κυματιστό έδαφος"
    return (f"Bakken μακρύ κατώφλι {n}×{m}'",
            f"Ζέσταμα 15 λεπτά. {n}×{m} λεπτά κάτω από το κατώφλι (80–85% των μέγιστων παλμών, ~2,5 mmol/L) {terr}, "
            f"με 90 δευτερόλεπτα πολύ αργό τρέξιμο ανάμεσα. Σταθερή ένταση, όχι αγώνας. 10 λεπτά αποψύχρανση.",
            "Το υπο-κατώφλι της νορβηγικής μεθόδου βελτιώνει την οικονομία του τρεξίματος, τη μιτοχονδριακή πυκνότητα και τον καθαρισμό "
            "του γαλακτικού με μικρό κόστος ανάκαμψης. Μαζί με μία συνεδρία VO2max και ~80% εύκολο όγκο ακολουθεί την πολωμένη κατανομή (Seiler, 2010).")


def mlr(phase: str, k: int, mode: str) -> tuple[str, str, str, int]:
    """Medium long run μέσα στην εβδομάδα: 90–120 λεπτά αερόβιο."""
    if phase == "taper":
        m = 60 if k >= 1 else 75
    elif mode == "down":
        m = 80
    elif phase == "base":
        m = min(105, 90 + 5 * (k // 2))
    elif phase == "build":
        m = min(120, 105 + 5 * (k // 2))
    else:
        m = 120
    h, mm = divmod(m, 60)
    lbl = f"{h}ώρ{f' {mm:02d}' if mm else ''}"
    terrain = "σε ανάγλυφο, με τις ανηφόρες σε γρήγορο περπάτημα" if phase == "specific" else "σε ήπιο ανάγλυφο"
    return (f"Medium long {lbl}",
            f"{m} λεπτά σταθερό αερόβιο τρέξιμο (ζώνη 1–2), {terrain}. Να μπορείς να μιλάς. Πάρε νερό και 30–60 g υδατάνθρακες την ώρα.",
            "Το medium-long μέσα στην εβδομάδα προσθέτει δεύτερο ερέθισμα αντοχής χωρίς την κούραση ενός δεύτερου μακριού (Pfitzinger & Douglas). "
            "Κρατιέται σε χαμηλή ένταση, σύμφωνα με την κατανομή ~80/20 (Seiler, 2010).",
            m)


