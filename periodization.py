"""Περιοδοποίηση για ορεινό αγώνα (π.χ. Olympus Marathon 44 km / +3350 m).

Εβδομάδα (ρυθμίζεται στο config.json → week_template):
    Δευ VO2max (q1) · Τρι γυμναστήριο · Τετ medium long · Πεμ εύκολο (≥40′) ·
    Παρ κατώφλι (q2) · Σαβ μακρύ (έως 3:00) · Κυρ ξεκούραση
Διαλειμματικές 1:30–1:45 συνολικά (λιγότερο μόνο στις ελαφριές εβδομάδες), μεσαίο μακρύ 1:30–2:00, με νορβηγικά πρωτόκολλα (Helgerud 4×4, Rønnestad 30/15, Bakken).

Φάσεις με βάση τις εβδομάδες μέχρι τον αγώνα:
    βάση (>20)     ανηφορικά σπριντ + tempo, πολύ αερόβιο
    ανάπτυξη (11–20) ανηφόρες VO2max + διαλείμματα κατωφλίου
    ειδική (3–10)  μεγάλες ανηφόρες στο κατώφλι + συνεχής ανάβαση/κατηφόρα
    taper (0–2)    ίδια ένταση, πολύ λιγότερος όγκος

Βιβλιογραφία που στηρίζει τις επιλογές (σύντομα στο πεδίο "why" κάθε ημέρας):
    Seiler 2010 (κατανομή έντασης ~80/20), Seiler et al. 2013 (4×8' με 2' παύση),
    Helgerud et al. 2007 (4×4'), Buchheit & Laursen 2013 (διαλείμματα υψηλής έντασης),
    Barnes et al. 2013 (ανηφορικά διαλείμματα και οικονομία), Paavolainen et al. 1999, Rønnestad et al. 2015 (30/15),
    Rønnestad & Mujika 2014, Blagrove et al. 2018 (βαριά δύναμη και οικονομία),
    McHugh 2003 (repeated bout effect στην εκκεντρική κόπωση), Bosquet et al. 2007 (taper),
    Pfitzinger & Douglas (medium-long run), Koop 2016 / Johnston & House 2019 (ορεινό τρέξιμο).
"""
